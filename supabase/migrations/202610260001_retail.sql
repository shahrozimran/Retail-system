-- Run once in Supabase SQL Editor (postgres role), then the private admin bootstrap.
-- All business mutations commit in one PostgreSQL transaction. No service-role key
-- is needed by the application: requests run with the signed-in user's JWT.
begin;

create schema retail_private;
revoke all on schema retail_private from public, anon, authenticated;
grant usage on schema retail_private to authenticated;

create table public.retail_admin (
  singleton boolean primary key default true check (singleton),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  email text not null check (length(email) between 3 and 254),
  active boolean not null default true
);

create table public.raw_materials (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 200),
  stock numeric(20,6) not null default 0 check (stock between 0 and 1000000000),
  created_at timestamptz not null default now()
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  sku text not null check (length(btrim(sku)) between 1 and 100),
  name text not null check (length(btrim(name)) between 1 and 200),
  category text not null default '' check (length(category) <= 100),
  buy_price numeric(16,2) not null check (buy_price between 0 and 1000000000),
  sale_price numeric(16,2) not null check (sale_price between 0 and 1000000000),
  quantity bigint not null default 0 check (quantity between 0 and 1000000000),
  min_stock bigint not null default 10 check (min_stock between 0 and 1000000000),
  status text not null default 'Active' check (status in ('Active','Low Stock','Out of Stock','Inactive','Discontinued','Archived')),
  created_at timestamptz not null default now()
);
create unique index products_sku_unique on public.products (lower(btrim(sku)));

create table public.product_materials (
  product_id uuid not null references public.products(id) on delete cascade,
  material_id uuid not null references public.raw_materials(id) on delete restrict,
  required_per_product numeric(20,6) not null check (required_per_product > 0 and required_per_product <= 1000000),
  primary key (product_id, material_id)
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 200),
  phone text not null default '' check (length(phone) <= 40),
  email text not null default '' check (length(email) <= 254 and (email='' or email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$')),
  current_balance numeric(18,2) not null default 0 check (current_balance between -1000000000000 and 1000000000000),
  status text not null default 'Active',
  created_at timestamptz not null default now()
);

create table public.sales_batches (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid references public.customers(id) on delete restrict,
  buyer_name text not null default '' check (length(buyer_name) <= 200),
  description text not null default '' check (length(description) <= 2000),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.transactions (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references public.sales_batches(id) on delete restrict,
  product_id uuid not null references public.products(id) on delete restrict,
  product_name text not null,
  product_sku text not null,
  type text not null check (type in ('In','Out')),
  quantity bigint not null check (quantity between 1 and 1000000),
  unit_price numeric(16,2) not null check (unit_price between 0 and 1000000000),
  total numeric(18,2) generated always as (quantity * unit_price) stored check (total between 0 and 1000000000000),
  created_at timestamptz not null default now()
);
create index transactions_by_date on public.transactions (created_at desc, id);
create index transactions_product on public.transactions (product_id);
create index batches_customer on public.sales_batches (customer_id);

create table public.finance_account (
  singleton boolean primary key default true check (singleton),
  balance numeric(18,2) not null default 0 check (balance between -1000000000000 and 1000000000000)
);
insert into public.finance_account (singleton) values (true);

create table public.finances (
  id bigint generated by default as identity primary key,
  transaction_id uuid unique references public.transactions(id) on delete restrict,
  category text not null,
  debit numeric(18,2) not null default 0 check (debit >= 0 and debit <= 1000000000000),
  credit numeric(18,2) not null default 0 check (credit >= 0 and credit <= 1000000000000),
  balance_snapshot numeric(18,2) not null check (balance_snapshot between -1000000000000 and 1000000000000),
  created_at timestamptz not null default now()
);

create table public.customer_ledger (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete restrict,
  batch_id uuid unique references public.sales_batches(id) on delete restrict,
  type text not null check (type in ('Receivable','Payable','Payment')),
  amount numeric(18,2) not null check (amount between 0 and 1000000000000),
  description text not null default '' check (length(description) <= 4096),
  balance_snapshot numeric(18,2) not null check (balance_snapshot between -1000000000000 and 1000000000000),
  created_at timestamptz not null default now()
);
create index customer_ledger_customer_date on public.customer_ledger (customer_id, created_at desc, id);

create table public.productions (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete restrict,
  product_name text not null,
  quantity bigint not null check (quantity between 1 and 1000000),
  materials_used jsonb not null check (jsonb_typeof(materials_used) = 'array'),
  cost_per_unit numeric(16,2) not null check (cost_per_unit between 0 and 1000000000),
  sale_per_unit numeric(16,2) not null check (sale_per_unit between 0 and 1000000000),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create table public.production_materials (
  production_id uuid not null references public.productions(id) on delete restrict,
  material_id uuid not null references public.raw_materials(id) on delete restrict,
  quantity numeric(20,6) not null check (quantity > 0 and quantity <= 1000000000),
  primary key (production_id, material_id)
);

create table public.operations (
  user_id uuid not null references auth.users(id) on delete restrict,
  request_id uuid not null,
  body_hash text not null,
  action text not null,
  result jsonb not null,
  created_at timestamptz not null default now(),
  primary key (user_id, request_id)
);
create table public.audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete restrict,
  request_id uuid not null,
  action text not null,
  record_id uuid,
  created_at timestamptz not null default now()
);

create function retail_private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.retail_admin a
    join auth.users u on u.id = a.user_id
    join auth.sessions s on s.user_id = a.user_id
    where a.singleton and a.active and a.user_id = (select auth.uid())
      and lower(u.email) = lower(a.email)
      and (u.banned_until is null or u.banned_until <= now())
      and (s.not_after is null or s.not_after > now())
      and s.id::text = (select auth.jwt() ->> 'session_id')
  );
$$;

create function retail_private.require_admin() returns void
language plpgsql stable security definer set search_path = '' as $$
begin
  if not retail_private.is_admin() then raise exception using errcode = '42501', message = 'Admin access is required.'; end if;
end;
$$;

-- Independent SQL validation protects direct RPC callers as well as the Next API.
create function retail_private.object(p jsonb) returns void
language plpgsql immutable set search_path = '' as $$
begin
  if jsonb_typeof(p) is distinct from 'object' then raise exception using errcode = '22023', message = 'A JSON object is required.'; end if;
end;
$$;

create function retail_private.text_field(p jsonb, k text, maximum integer, required boolean default true) returns text
language plpgsql immutable set search_path = '' as $$
declare v text;
begin
  if not required and not (p ? k) then return ''; end if;
  if jsonb_typeof(p -> k) is distinct from 'string' then raise exception using errcode = '22023', message = 'Invalid text field: ' || k; end if;
  v := btrim(p ->> k);
  if length(v) > maximum or (required and v !~ '[^[:space:]]') or regexp_replace(v,E'[\n\r\t]','','g') ~ '[[:cntrl:]]' then
    raise exception using errcode = '22023', message = 'Invalid text field: ' || k;
  end if;
  return v;
end;
$$;

create function retail_private.num(p jsonb, k text, minimum numeric, maximum numeric, integral boolean default false, decimals integer default 6) returns numeric
language plpgsql immutable set search_path = '' as $$
declare v numeric;
begin
  if jsonb_typeof(p -> k) is distinct from 'number' then raise exception using errcode = '22023', message = 'Invalid numeric field: ' || k; end if;
  v := (p ->> k)::numeric;
  if v < minimum or v > maximum or v <> round(v, decimals) or (integral and v <> trunc(v)) then
    raise exception using errcode = '22023', message = 'Invalid numeric field: ' || k;
  end if;
  return v;
end;
$$;

create function retail_private.uuid_field(p jsonb, k text, optional boolean default false) returns uuid
language plpgsql immutable set search_path = '' as $$
begin
  if optional and (not (p ? k) or p ->> k = '') then return null; end if;
  if jsonb_typeof(p -> k) is distinct from 'string' or (p ->> k) !~* '^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$' then
    raise exception using errcode = '22023', message = 'Invalid identifier: ' || k;
  end if;
  return (p ->> k)::uuid;
end;
$$;

create function retail_private.keys(p jsonb, allowed text[]) returns void
language plpgsql immutable set search_path = '' as $$
begin
  perform retail_private.object(p);
  if exists (select 1 from jsonb_object_keys(p) k where not (k = any(allowed))) then
    raise exception using errcode = '22023', message = 'Unknown request field.';
  end if;
end;
$$;

create function retail_private.stock_status(q bigint, minimum bigint, status text) returns text
language sql immutable set search_path = '' as $$
  select case when status not in ('Active','Low Stock','Out of Stock') then status
    when q = 0 then 'Out of Stock' when q <= minimum then 'Low Stock' else 'Active' end;
$$;

create function retail_private.product_json(p public.products) returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'uuid', p.id, 'sku', p.sku, 'name', p.name, 'category', p.category,
    'buyPrice', p.buy_price, 'salePrice', p.sale_price, 'quantity', p.quantity,
    'minStock', p.min_stock, 'status', retail_private.stock_status(p.quantity,p.min_stock,p.status),
    'potentialQuantity', coalesce((select min(floor(r.stock / m.required_per_product)) from public.product_materials m join public.raw_materials r on r.id=m.material_id where m.product_id=p.id),0),
    'rawMaterials', coalesce((select jsonb_agg(jsonb_build_object('uuid',r.id,'name',r.name,'quantity',r.stock,'requiredPerProduct',m.required_per_product) order by r.id)
      from public.product_materials m join public.raw_materials r on r.id=m.material_id where m.product_id=p.id),'[]'::jsonb)
  );
$$;

create function public.retail_session() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  perform retail_private.require_admin();
  return jsonb_build_object('success',true,'username',(select a.email from public.retail_admin a where a.singleton),'userId',auth.uid());
end;
$$;

create function public.retail_read(p_action text, p_customer_uuid uuid default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare data jsonb;
begin
  perform retail_private.require_admin();
  case p_action
    when 'dashboard' then
      select jsonb_build_object(
        'products',coalesce((select jsonb_agg(retail_private.product_json(p) order by p.created_at,p.id) from public.products p),'[]'::jsonb),
        'totalInventoryValue',coalesce((select sum(p.quantity*p.buy_price) from public.products p),0),
        'totalBalance',(select balance from public.finance_account where singleton),
        'activeAlerts',(select count(*) from public.products where quantity <= min_stock)
      ) into data;
    when 'products' then select coalesce(jsonb_agg(retail_private.product_json(p) order by p.created_at,p.id),'[]'::jsonb) into data from public.products p;
    when 'raw_materials' then select coalesce(jsonb_agg(jsonb_build_object('uuid',r.id,'name',r.name,'stock',r.stock) order by r.created_at,r.id),'[]'::jsonb) into data from public.raw_materials r;
    when 'customers' then select coalesce(jsonb_agg(jsonb_build_object('uuid',c.id,'name',c.name,'phone',c.phone,'email',c.email,'balance',c.current_balance,'status',c.status) order by c.created_at,c.id),'[]'::jsonb) into data from public.customers c;
    when 'transactions' then
      select coalesce(jsonb_agg(jsonb_build_object('id',t.id,'date',t.created_at,'productUuid',t.product_id,'productName',t.product_name,'productSku',t.product_sku,
        'type',t.type,'qtyChange',t.quantity,'unitPrice',t.unit_price,'total',t.total,'description',b.description,'buyerName',b.buyer_name,'batchId',b.id,'customerUuid',coalesce(b.customer_id::text,'')) order by t.created_at desc,t.id),'[]'::jsonb)
      into data from public.transactions t join public.sales_batches b on b.id=t.batch_id;
    when 'reports' then select coalesce(jsonb_agg(jsonb_build_object('date',f.created_at,'category',f.category,'debit',f.debit,'credit',f.credit,'balanceSnapshot',f.balance_snapshot) order by f.created_at desc,f.id desc),'[]'::jsonb) into data from public.finances f;
    when 'productions' then select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'date',p.created_at,'productUuid',p.product_id,'productName',p.product_name,'qtyProduced',p.quantity,'rawMaterialsUsed',p.materials_used,'costPerUnit',p.cost_per_unit,'salePerUnit',p.sale_per_unit) order by p.created_at desc,p.id),'[]'::jsonb) into data from public.productions p;
    when 'customer_ledger' then
      if p_customer_uuid is null then raise exception using errcode='22023',message='Customer identifier is required.'; end if;
      select coalesce(jsonb_agg(jsonb_build_object('id',l.id,'date',l.created_at,'customerUuid',l.customer_id,'type',l.type,'amount',l.amount,'description',l.description,'balanceSnapshot',l.balance_snapshot) order by l.created_at desc,l.id),'[]'::jsonb) into data from public.customer_ledger l where l.customer_id=p_customer_uuid;
    else raise exception using errcode='22023',message='Unknown read action.';
  end case;
  return jsonb_build_object('success',true,'data',data);
end;
$$;

create function public.retail_mutate(p_payload jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
<<v>>
declare
  action text; request_id uuid; body_hash text; old_operation public.operations%rowtype;
  record_id uuid; product public.products%rowtype; material public.raw_materials%rowtype;
  item jsonb; recipe jsonb; items jsonb; used jsonb := '[]'::jsonb;
  quantity bigint; price numeric; total numeric; balance numeric; net numeric := 0;
  customer_id uuid; customer_balance numeric; batch_id uuid; transaction_id uuid;
  stock numeric; requirement numeric; kind text; status text; amount numeric; result jsonb;
  fields text[]; seen uuid[] := '{}'::uuid[]; material_id uuid;
begin
  perform retail_private.require_admin();
  perform retail_private.object(p_payload);
  if octet_length(p_payload::text)>65536 then raise exception using errcode='22023',message='Request is too large.'; end if;
  action := retail_private.text_field(p_payload,'action',50);
  request_id := retail_private.uuid_field(p_payload,'requestId');
  body_hash := encode(sha256(convert_to((p_payload - 'requestId' - 'requestedAt')::text,'UTF8')),'hex');
  -- A transaction-scoped lock serializes complex inventory/ledger mutations and
  -- same-ID retries without holding any connection between Vercel requests.
  perform pg_advisory_xact_lock(723901642);
  select * into old_operation from public.operations o where o.user_id=auth.uid() and o.request_id=v.request_id;
  if found then
    if old_operation.body_hash<>body_hash then raise exception using errcode='23505',message='Operation identifier belongs to different data.'; end if;
    return old_operation.result;
  end if;
  perform retail_private.num(p_payload,'requestedAt',extract(epoch from now()-interval '24 hours')*1000,extract(epoch from now()+interval '5 minutes')*1000,true,0);
  fields := case action
    when 'add_product' then array['productUuid','sku','name','category','buyPrice','salePrice','quantity','minStock','status','rawMaterials']
    when 'update_product' then array['productUuid','sku','name','category','buyPrice','salePrice','quantity','minStock','status','rawMaterials']
    when 'delete_product' then array['productUuid']
    when 'add_raw_material' then array['uuid','name','stock']
    when 'update_raw_material' then array['uuid','name','stock']
    when 'delete_raw_material' then array['uuid']
    when 'add_customer' then array['name','phone','email']
    when 'delete_customer' then array['customerUuid']
    when 'record_customer_payment' then array['customerUuid','type','amount','description']
    when 'transaction' then array['productUuid','type','qtyChange','unitPrice','buyerName','description']
    when 'batch_transaction' then array['items','customerUuid','buyerName','description']
    when 'process_production' then array['productUuid','qtyProduced']
    else null end;
  if fields is null then raise exception using errcode='22023',message='Unknown or immutable action.'; end if;
  perform retail_private.keys(p_payload,fields || array['action','requestId','requestedAt']);

  case
  when action in ('add_raw_material','update_raw_material') then
    stock := retail_private.num(p_payload,'stock',0,1000000000);
    if action='add_raw_material' then
      perform retail_private.uuid_field(p_payload,'uuid',true);
      insert into public.raw_materials(name,stock) values(retail_private.text_field(p_payload,'name',200),stock) returning id into record_id;
    else
      record_id := retail_private.uuid_field(p_payload,'uuid');
      update public.raw_materials r set name=retail_private.text_field(p_payload,'name',200),stock=v.stock where r.id=record_id;
      if not found then raise exception using errcode='22023',message='Raw material not found.'; end if;
    end if;
  when action='delete_raw_material' then
    record_id := retail_private.uuid_field(p_payload,'uuid');
    delete from public.raw_materials where id=record_id;
    if not found then raise exception using errcode='22023',message='Raw material not found.'; end if;
  when action in ('add_product','update_product') then
    status := retail_private.text_field(p_payload,'status',30);
    if status not in ('Active','Low Stock','Out of Stock','Inactive','Discontinued','Archived') then raise exception using errcode='22023',message='Invalid product status.'; end if;
    quantity := retail_private.num(p_payload,'quantity',0,1000000000,true,0);
    perform retail_private.num(p_payload,'buyPrice',0,1000000000,false,2);
    perform retail_private.num(p_payload,'salePrice',0,1000000000,false,2);
    perform retail_private.num(p_payload,'minStock',0,1000000000,true,0);
    recipe := coalesce(p_payload->'rawMaterials','[]'::jsonb);
    if jsonb_typeof(recipe)<>'array' or jsonb_array_length(recipe)>50 then raise exception using errcode='22023',message='Invalid recipe.'; end if;
    if action='add_product' then
      perform retail_private.uuid_field(p_payload,'productUuid',true);
      insert into public.products(sku,name,category,buy_price,sale_price,quantity,min_stock,status)
      values(retail_private.text_field(p_payload,'sku',100),retail_private.text_field(p_payload,'name',200),retail_private.text_field(p_payload,'category',100,false),
        (p_payload->>'buyPrice')::numeric,(p_payload->>'salePrice')::numeric,quantity,(p_payload->>'minStock')::bigint,status) returning id into record_id;
    else
      record_id := retail_private.uuid_field(p_payload,'productUuid');
      select * into product from public.products where id=record_id for update;
      if not found then raise exception using errcode='22023',message='Product not found.'; end if;
      if product.quantity<>quantity then raise exception using errcode='23505',message='Stock has changed. Refresh before editing.'; end if;
      update public.products p set sku=retail_private.text_field(p_payload,'sku',100),name=retail_private.text_field(p_payload,'name',200),category=retail_private.text_field(p_payload,'category',100,false),
        buy_price=(p_payload->>'buyPrice')::numeric,sale_price=(p_payload->>'salePrice')::numeric,min_stock=(p_payload->>'minStock')::bigint,status=v.status where p.id=record_id;
      delete from public.product_materials where product_id=record_id;
    end if;
    for item in select value from jsonb_array_elements(recipe) loop
      perform retail_private.keys(item,array['uuid','name','quantity','requiredPerProduct']);
      material_id := retail_private.uuid_field(item,'uuid');
      requirement := retail_private.num(item,'requiredPerProduct',0.000001,1000000);
      if item ? 'name' then perform retail_private.text_field(item,'name',200,false); end if;
      if item ? 'quantity' then perform retail_private.num(item,'quantity',0,1000000000); end if;
      if material_id=any(seen) then raise exception using errcode='22023',message='Recipe materials must be unique.'; end if;
      seen := array_append(seen,material_id);
      insert into public.product_materials(product_id,material_id,required_per_product) values(record_id,material_id,requirement);
    end loop;
  when action='delete_product' then
    record_id := retail_private.uuid_field(p_payload,'productUuid');
    delete from public.products where id=record_id;
    if not found then raise exception using errcode='22023',message='Product not found.'; end if;
  when action='add_customer' then
    insert into public.customers(name,phone,email) values(retail_private.text_field(p_payload,'name',200),retail_private.text_field(p_payload,'phone',40,false),retail_private.text_field(p_payload,'email',254,false)) returning id into record_id;
  when action='delete_customer' then
    record_id := retail_private.uuid_field(p_payload,'customerUuid');
    select current_balance into customer_balance from public.customers where id=record_id for update;
    if not found then raise exception using errcode='22023',message='Customer not found.'; end if;
    if customer_balance<>0 then raise exception using errcode='23505',message='Customers with balances cannot be deleted.'; end if;
    delete from public.customers where id=record_id;
  when action='record_customer_payment' then
    record_id := retail_private.uuid_field(p_payload,'customerUuid');
    amount := retail_private.num(p_payload,'amount',0.01,1000000000,false,2);
    kind := retail_private.text_field(p_payload,'type',20);
    if kind not in ('Receivable','Payable','Payment') then raise exception using errcode='22023',message='Invalid ledger type.'; end if;
    update public.customers c set current_balance=c.current_balance+case when kind='Receivable' then amount else -amount end where c.id=record_id returning current_balance into customer_balance;
    if not found then raise exception using errcode='22023',message='Customer not found.'; end if;
    insert into public.customer_ledger(customer_id,type,amount,description,balance_snapshot) values(record_id,kind,amount,retail_private.text_field(p_payload,'description',2000,false),customer_balance);
  when action in ('transaction','batch_transaction') then
    items := case when action='transaction' then jsonb_build_array(jsonb_build_object('productUuid',p_payload->'productUuid','type',p_payload->'type','qtyChange',p_payload->'qtyChange','unitPrice',p_payload->'unitPrice')) else p_payload->'items' end;
    if jsonb_typeof(items) is distinct from 'array' or jsonb_array_length(items) not between 1 and 100 then raise exception using errcode='22023',message='An order must contain 1 to 100 items.'; end if;
    customer_id := case when action='batch_transaction' then retail_private.uuid_field(p_payload,'customerUuid',true) else null end;
    if customer_id is not null then
      perform 1 from public.customers where id=customer_id for update;
      if not found then raise exception using errcode='22023',message='Customer not found.'; end if;
    end if;
    insert into public.sales_batches(customer_id,buyer_name,description,created_by) values(customer_id,retail_private.text_field(p_payload,'buyerName',200,false),retail_private.text_field(p_payload,'description',2000,false),auth.uid()) returning id into batch_id;
    record_id := batch_id;
    select f.balance into balance from public.finance_account f where singleton for update;
    for item in select value from jsonb_array_elements(items) loop
      perform retail_private.keys(item,array['productUuid','type','qtyChange','unitPrice']);
      select * into product from public.products where id=retail_private.uuid_field(item,'productUuid') for update;
      if not found then raise exception using errcode='22023',message='Product not found.'; end if;
      quantity := retail_private.num(item,'qtyChange',1,1000000,true,0);
      price := retail_private.num(item,'unitPrice',0,1000000000,false,2);
      kind := retail_private.text_field(item,'type',3);
      if kind not in ('In','Out') then raise exception using errcode='22023',message='Invalid transaction type.'; end if;
      total := quantity*price;
      if total>1000000000000 then raise exception using errcode='22023',message='Order item total is too large.'; end if;
      if kind='Out' and product.quantity<quantity then raise exception using errcode='23505',message='Insufficient stock.'; end if;
      update public.products p set quantity=p.quantity+case when kind='Out' then -v.quantity else v.quantity end where p.id=product.id;
      insert into public.transactions(batch_id,product_id,product_name,product_sku,type,quantity,unit_price) values(batch_id,product.id,product.name,product.sku,kind,quantity,price) returning id into transaction_id;
      balance := balance+case when kind='Out' then total else -total end;
      net := net+case when kind='Out' then total else -total end;
      insert into public.finances(transaction_id,category,debit,credit,balance_snapshot) values(transaction_id,case when kind='Out' then 'Sales' else 'Expenses' end,case when kind='In' then total else 0 end,case when kind='Out' then total else 0 end,balance);
    end loop;
    update public.finance_account f set balance=v.balance where singleton;
    if customer_id is not null then
      update public.customers c set current_balance=c.current_balance+net where c.id=customer_id returning current_balance into customer_balance;
      insert into public.customer_ledger(customer_id,batch_id,type,amount,description,balance_snapshot) values(customer_id,batch_id,case when net>=0 then 'Receivable' else 'Payable' end,abs(net),'Order: '||batch_id::text,customer_balance);
    end if;
  when action='process_production' then
    select * into product from public.products where id=retail_private.uuid_field(p_payload,'productUuid') for update;
    if not found then raise exception using errcode='22023',message='Product not found.'; end if;
    quantity := retail_private.num(p_payload,'qtyProduced',1,1000000,true,0);
    for item in select jsonb_build_object('id',m.material_id,'required',m.required_per_product) from public.product_materials m where m.product_id=product.id order by m.material_id loop
      select * into material from public.raw_materials where id=(item->>'id')::uuid for update;
      requirement := (item->>'required')::numeric*quantity;
      if requirement>material.stock then raise exception using errcode='23505',message='Insufficient raw material stock.'; end if;
      update public.raw_materials r set stock=r.stock-requirement where r.id=material.id;
      used := used||jsonb_build_array(jsonb_build_object('uuid',material.id,'name',material.name,'qtyUsed',requirement));
    end loop;
    if jsonb_array_length(used)=0 then raise exception using errcode='22023',message='Configure a production recipe first.'; end if;
    update public.products p set quantity=p.quantity+v.quantity where p.id=product.id;
    insert into public.productions(product_id,product_name,quantity,materials_used,cost_per_unit,sale_per_unit,created_by) values(product.id,product.name,quantity,used,product.buy_price,product.sale_price,auth.uid()) returning id into record_id;
    insert into public.production_materials(production_id,material_id,quantity) select record_id,(v->>'uuid')::uuid,(v->>'qtyUsed')::numeric from jsonb_array_elements(used) v;
  else raise exception using errcode='22023',message='Unknown action.';
  end case;

  result := jsonb_build_object('success',true,'message','Operation completed.','uuid',record_id);
  insert into public.operations(user_id,request_id,body_hash,action,result) values(auth.uid(),request_id,body_hash,action,result);
  insert into public.audit_log(user_id,request_id,action,record_id) values(auth.uid(),request_id,action,record_id);
  return result;
end;
$$;

