create or replace function retail_private.correct_transaction(p_payload jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
<<v>>
declare
  action text; request_id uuid; body_hash text; old_operation public.operations%rowtype;
  batch public.sales_batches%rowtype; target public.transactions%rowtype;
  old_items jsonb; new_items jsonb := '[]'::jsonb; supplied_items jsonb;
  before_state jsonb; after_state jsonb; item jsonb; prior public.transactions%rowtype;
  product public.products%rowtype; customer public.customers%rowtype;
  batch_id uuid; target_id uuid; item_id uuid; product_id uuid; customer_id uuid;
  expected_revision bigint; quantity bigint; price numeric; kind text; reason text;
  buyer_name text; description text; old_net numeric; new_net numeric := 0;
  finance_base numeric; customer_bases jsonb := '{}'::jsonb; affected uuid[] := '{}'::uuid[];
  seen uuid[] := '{}'::uuid[]; deleting boolean; result jsonb; stock_change record;
begin
  perform retail_private.require_admin();
  perform retail_private.object(p_payload);
  if octet_length(p_payload::text)>65536 then raise exception using errcode='22023',message='Request is too large.'; end if;
  action := retail_private.text_field(p_payload,'action',50);
  request_id := retail_private.uuid_field(p_payload,'requestId');
  body_hash := encode(sha256(convert_to((p_payload - 'requestId' - 'requestedAt')::text,'UTF8')),'hex');
  -- Same lock as the original posting RPC: corrections and new postings serialize.
  perform pg_advisory_xact_lock(723901642);
  select * into old_operation from public.operations o where o.user_id=auth.uid() and o.request_id=v.request_id;
  if found then
    if old_operation.body_hash<>body_hash then raise exception using errcode='23505',message='Operation identifier belongs to different data.'; end if;
    return old_operation.result;
  end if;
  perform retail_private.num(p_payload,'requestedAt',extract(epoch from now()-interval '24 hours')*1000,extract(epoch from now()+interval '5 minutes')*1000,true,0);
  perform retail_private.keys(p_payload, array['action','requestId','requestedAt','expectedRevision','reason'] || case action
    when 'update_transaction_batch' then array['batchId','items','customerUuid','buyerName','description']
    when 'delete_transaction_batch' then array['batchId']
    when 'update_transaction' then array['transactionId','productUuid','type','qtyChange','unitPrice']
    when 'delete_transaction' then array['transactionId']
    else array[]::text[] end);
  if action not in ('update_transaction','delete_transaction','update_transaction_batch','delete_transaction_batch') then
    raise exception using errcode='22023',message='Unknown correction action.';
  end if;
  expected_revision := retail_private.num(p_payload,'expectedRevision',1,9007199254740991,true,0);
  reason := retail_private.text_field(p_payload,'reason',1000);
  if action in ('update_transaction','delete_transaction') then
    target_id := retail_private.uuid_field(p_payload,'transactionId');
    select * into target from public.transactions t where t.id=target_id;
    if not found then raise exception using errcode='22023',message='Transaction not found. Refresh the transaction list.'; end if;
    batch_id := target.batch_id;
  else
    batch_id := retail_private.uuid_field(p_payload,'batchId');
  end if;
  select * into batch from public.sales_batches b where b.id=v.batch_id for update;
  if not found then raise exception using errcode='22023',message='Order not found. Refresh the transaction list.'; end if;
  if batch.revision<>expected_revision then raise exception using errcode='23505',message='This order changed in another window. Refresh before editing or deleting it.'; end if;
  select coalesce(jsonb_agg(to_jsonb(t) order by t.created_at,t.id),'[]'::jsonb), coalesce(sum(case when t.type='Out' then t.total else -t.total end),0)
    into old_items,old_net from public.transactions t where t.batch_id=v.batch_id;
  if jsonb_array_length(old_items)=0 then raise exception using errcode='22023',message='The order has no transaction entries.'; end if;
  if (select count(*) from public.finances f join public.transactions t on t.id=f.transaction_id where t.batch_id=v.batch_id)<>jsonb_array_length(old_items) then
    raise exception using errcode='23505',message='The linked finance records are incomplete. Review the order before correcting it.';
  end if;
  if batch.customer_id is not null and not exists(select 1 from public.customer_ledger l where l.batch_id=v.batch_id and l.customer_id=batch.customer_id) then
    raise exception using errcode='23505',message='The linked customer ledger is incomplete. Review the order before correcting it.';
  end if;
  before_state := jsonb_build_object('batch',to_jsonb(batch),'transactions',old_items,
    'finances',(select coalesce(jsonb_agg(to_jsonb(f) order by f.id),'[]'::jsonb) from public.finances f join public.transactions t on t.id=f.transaction_id where t.batch_id=v.batch_id),
    'customerLedger',(select coalesce(jsonb_agg(to_jsonb(l)),'[]'::jsonb) from public.customer_ledger l where l.batch_id=v.batch_id));

  customer_id := batch.customer_id; buyer_name := batch.buyer_name; description := batch.description;
  if action='update_transaction_batch' then
    customer_id := retail_private.uuid_field(p_payload,'customerUuid',true);
    buyer_name := retail_private.text_field(p_payload,'buyerName',200,false);
    description := retail_private.text_field(p_payload,'description',2000,false);
    supplied_items := p_payload->'items';
    if jsonb_typeof(supplied_items) is distinct from 'array' or jsonb_array_length(supplied_items) not between 1 and 100 then
      raise exception using errcode='22023',message='An order must contain 1 to 100 items.';
    end if;
  elsif action='delete_transaction_batch' then
    supplied_items := '[]'::jsonb;
  else
    select coalesce(jsonb_agg(case when t.id=target_id and action='update_transaction' then
      jsonb_build_object('id',t.id,'productUuid',p_payload->'productUuid','type',p_payload->'type','qtyChange',p_payload->'qtyChange','unitPrice',p_payload->'unitPrice')
      else jsonb_build_object('id',t.id,'productUuid',t.product_id,'type',t.type,'qtyChange',t.quantity,'unitPrice',t.unit_price) end order by t.created_at,t.id),'[]'::jsonb)
      into supplied_items from public.transactions t where t.batch_id=v.batch_id and not (action='delete_transaction' and t.id=target_id);
  end if;
  deleting := jsonb_array_length(supplied_items)=0;
  if deleting then customer_id := null; end if;
  if customer_id is not null and not exists(select 1 from public.customers c where c.id=v.customer_id) then
    raise exception using errcode='22023',message='Customer not found.';
  end if;

  for item in select value from jsonb_array_elements(supplied_items) loop
    perform retail_private.keys(item,array['id','productUuid','type','qtyChange','unitPrice']);
    prior := null;
    if item ? 'id' then
      item_id := retail_private.uuid_field(item,'id');
      select * into prior from public.transactions t where t.id=item_id and t.batch_id=v.batch_id;
      if not found then raise exception using errcode='22023',message='An item does not belong to this order.'; end if;
    else
      item_id := gen_random_uuid();
    end if;
    if item_id=any(seen) then raise exception using errcode='22023',message='An order item was supplied more than once.'; end if;
    seen := array_append(seen,item_id);
    product_id := retail_private.uuid_field(item,'productUuid');
    select * into product from public.products p where p.id=v.product_id;
    if not found then raise exception using errcode='22023',message='Product not found.'; end if;
    quantity := retail_private.num(item,'qtyChange',1,1000000,true,0);
    price := retail_private.num(item,'unitPrice',0,1000000000,false,2);
    kind := retail_private.text_field(item,'type',3);
    if kind not in ('In','Out') then raise exception using errcode='22023',message='Invalid transaction type.'; end if;
    if quantity*price>1000000000000 then raise exception using errcode='22023',message='Order item total is too large.'; end if;
    new_net := new_net+case when kind='Out' then quantity*price else -quantity*price end;
    new_items := new_items || jsonb_build_array(jsonb_build_object('id',item_id,'product_id',product_id,
      'product_name',case when prior.product_id=product_id then prior.product_name else product.name end,
      'product_sku',case when prior.product_id=product_id then prior.product_sku else product.sku end,
      'type',kind,'quantity',quantity,'unit_price',price,'created_at',coalesce(prior.created_at,batch.created_at)));
  end loop;

  -- Calculate final stock per product before updating it. Reversing a purchase
  -- temporarily could go negative even when the final edited order is valid.
  for stock_change in
    select movements.product_id,sum(movements.delta) as delta from (
      select t.product_id,case when t.type='Out' then t.quantity else -t.quantity end as delta from public.transactions t where t.batch_id=v.batch_id
      union all
      select (i->>'product_id')::uuid,case when i->>'type'='Out' then -(i->>'quantity')::bigint else (i->>'quantity')::bigint end from jsonb_array_elements(new_items) i
    ) movements group by movements.product_id order by movements.product_id
  loop
    select * into product from public.products p where p.id=stock_change.product_id for update;
    if product.quantity+stock_change.delta<0 then
      raise exception using errcode='23505',message='This correction would leave insufficient stock. Stock received by this order may already have been used.';
    end if;
    update public.products p set quantity=p.quantity+stock_change.delta where p.id=stock_change.product_id;
  end loop;

  select f.balance-coalesce((select sum(x.credit-x.debit) from public.finances x),0) into finance_base from public.finance_account f where f.singleton for update;
  update public.finance_account f set balance=f.balance+new_net-old_net where f.singleton;
  -- Keep any existing opening adjustment rather than assuming every balance is 0.
  for customer in select c.* from public.customers c where c.id=batch.customer_id or c.id=v.customer_id order by c.id for update loop
    affected := array_append(affected,customer.id);
    customer_bases := customer_bases || jsonb_build_object(customer.id::text,customer.current_balance-coalesce((select sum(case when l.type='Receivable' then l.amount else -l.amount end) from public.customer_ledger l where l.customer_id=customer.id),0));
    update public.customers c set current_balance=c.current_balance
      -case when c.id=batch.customer_id then old_net else 0 end
      +case when c.id=v.customer_id then new_net else 0 end where c.id=customer.id;
  end loop;

  delete from public.finances f using public.transactions t where f.transaction_id=t.id and t.batch_id=v.batch_id and not(t.id=any(seen));
  delete from public.transactions t where t.batch_id=v.batch_id and not(t.id=any(seen));
  for item in select value from jsonb_array_elements(new_items) loop
    item_id := (item->>'id')::uuid;
    insert into public.transactions(id,batch_id,product_id,product_name,product_sku,type,quantity,unit_price,created_at)
      values(item_id,batch_id,(item->>'product_id')::uuid,item->>'product_name',item->>'product_sku',item->>'type',(item->>'quantity')::bigint,(item->>'unit_price')::numeric,(item->>'created_at')::timestamptz)
      on conflict(id) do update set product_id=excluded.product_id,product_name=excluded.product_name,product_sku=excluded.product_sku,type=excluded.type,quantity=excluded.quantity,unit_price=excluded.unit_price;
    insert into public.finances(transaction_id,category,debit,credit,balance_snapshot,created_at)
      values(item_id,case when item->>'type'='Out' then 'Sales' else 'Expenses' end,
        case when item->>'type'='In' then (item->>'quantity')::numeric*(item->>'unit_price')::numeric else 0 end,
        case when item->>'type'='Out' then (item->>'quantity')::numeric*(item->>'unit_price')::numeric else 0 end,0,(item->>'created_at')::timestamptz)
      on conflict(transaction_id) do update set category=excluded.category,debit=excluded.debit,credit=excluded.credit;
  end loop;
  delete from public.customer_ledger l where l.batch_id=v.batch_id and (v.customer_id is null or l.customer_id<>v.customer_id);
  if customer_id is not null then
    insert into public.customer_ledger(customer_id,batch_id,type,amount,description,balance_snapshot,created_at)
      values(customer_id,batch_id,case when new_net>=0 then 'Receivable' else 'Payable' end,abs(new_net),'Order: '||batch_id::text,0,batch.created_at)
      on conflict on constraint customer_ledger_batch_id_key do update set type=excluded.type,amount=excluded.amount,description=excluded.description;
  end if;
  if deleting then
    delete from public.sales_batches b where b.id=v.batch_id;
    after_state := null;
  else
    update public.sales_batches b set customer_id=v.customer_id,buyer_name=v.buyer_name,description=v.description,revision=b.revision+1 where b.id=v.batch_id;
  end if;

  -- Rebuild running snapshots, including later entries, in their original order.
  with snapshots as (
    select f.id,finance_base+sum(f.credit-f.debit) over(order by f.created_at,f.id rows between unbounded preceding and current row) as balance
    from public.finances f
  ) update public.finances f set balance_snapshot=s.balance from snapshots s where f.id=s.id;
  with snapshots as (
    select l.id,(customer_bases->>l.customer_id::text)::numeric+
      sum(case when l.type='Receivable' then l.amount else -l.amount end) over(partition by l.customer_id order by l.created_at,l.id rows between unbounded preceding and current row) as balance
    from public.customer_ledger l where l.customer_id=any(affected)
  ) update public.customer_ledger l set balance_snapshot=s.balance from snapshots s where l.id=s.id;
  if not deleting then
    after_state := jsonb_build_object('batch',(select to_jsonb(b) from public.sales_batches b where b.id=v.batch_id),
      'transactions',(select jsonb_agg(to_jsonb(t) order by t.created_at,t.id) from public.transactions t where t.batch_id=v.batch_id),
      'finances',(select jsonb_agg(to_jsonb(f) order by f.id) from public.finances f join public.transactions t on t.id=f.transaction_id where t.batch_id=v.batch_id),
      'customerLedger',(select coalesce(jsonb_agg(to_jsonb(l)),'[]'::jsonb) from public.customer_ledger l where l.batch_id=v.batch_id));
  end if;
  result := jsonb_build_object('success',true,'message',case when deleting then 'Transaction deleted and linked balances updated.' else 'Transaction updated and linked balances updated.' end,
    'uuid',batch_id,'batchId',batch_id,'transactionId',target_id,'deleted',deleting,'revision',case when deleting then null else batch.revision+1 end,'customerUuids',to_jsonb(affected));
  insert into public.operations(user_id,request_id,body_hash,action,result) values(auth.uid(),request_id,body_hash,action,result);
  insert into public.audit_log(user_id,request_id,action,record_id) values(auth.uid(),request_id,action,batch_id);
  insert into public.transaction_changes(user_id,request_id,batch_id,action,reason,before_state,after_state) values(auth.uid(),request_id,batch_id,action,reason,before_state,after_state);
  return result;
end;
$$;
revoke all on function retail_private.correct_transaction(jsonb) from public, anon, authenticated;

create or replace function public.retail_mutate(p_payload jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
begin
  if p_payload->>'action' in ('update_transaction','delete_transaction','update_transaction_batch','delete_transaction_batch') then
    return retail_private.correct_transaction(p_payload);
  end if;
  return retail_private.retail_mutate(p_payload);
end;
$$;
revoke all on function public.retail_mutate(jsonb) from public, anon, authenticated;
grant execute on function public.retail_mutate(jsonb) to authenticated;

-- All transaction rows expose their order revision for stale-edit protection.
create or replace function public.retail_read(p_action text,p_customer_uuid uuid default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare result jsonb;
begin
  result := retail_private.retail_read(p_action,p_customer_uuid);
  if p_action='transactions' then
    result := jsonb_set(result,'{data}',coalesce((select jsonb_agg(e.item||jsonb_build_object('revision',b.revision) order by e.position)
      from jsonb_array_elements(result->'data') with ordinality e(item,position)
      join public.sales_batches b on b.id=(e.item->>'batchId')::uuid),'[]'::jsonb));
  end if;
  return result;
end;
$$;
revoke all on function public.retail_read(text,uuid) from public, anon, authenticated;
grant execute on function public.retail_read(text,uuid) to authenticated;

